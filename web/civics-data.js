//
// `kind` is the important field:
//   static — the answer does not change. 120 of the 128.
//   lookup — the answer changes with elections, appointments, or where
//            you live, so NO answer is stored. Shipping a fixed answer
//            for "who is the President now" means confidently teaching
//            the wrong one the day after an election. These link to the
//            USCIS updates page instead of being scored.
//
// `answers` is a SET, and any member is correct — which is how the real
// interview works, where the officer accepts any valid answer. 80 of the
// 128 have more than one; question 117 has twenty-five.
//
// `need` is how many items the question actually asks for. Most want one,
// but seven want two, three or five — "Name two promises...", "Name five
// of the original states". Treating those as one-and-done marked them
// correct after a single pick, which is not what the interview asks.
//
// `cat` is what KIND of thing the answer is, taken from the question stem
