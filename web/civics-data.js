// war is offered against other wars, so answering needs actual knowledge
// rather than noticing that four options are not wars. Derived FORM-FIRST
// — "Why did the US enter the Korean War" is about a war but its answer is
// a reason, and getting that backwards offered Vietnam as a distractor for
// a question about motives.
//
